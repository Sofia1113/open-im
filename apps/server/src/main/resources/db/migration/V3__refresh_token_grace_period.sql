-- 刷新令牌轮换宽限期
--
-- 纯粹的"一次性使用"轮换在真实客户端上会误伤：用户开两个标签页、
-- 网络重试、或请求成功但响应丢失时，同一个刷新令牌会被提交两次，
-- 第二次要么被拒绝（用户莫名登出），要么被判定为重放（设备被撤销）。
--
-- 保留上一个令牌的哈希并给它一个短暂的宽限窗口后：
--   * 窗口内出现的上一个令牌 → 视为正常的并发/重试，允许再次交换
--   * 窗口外出现的上一个令牌，或更早的令牌 → 判定为重放，撤销设备
--
-- 攻击者窃取令牌后通常在更晚的时间使用，因此宽限期在保留检测能力的同时
-- 消除了绝大部分误判。

ALTER TABLE devices
    ADD COLUMN previous_refresh_token_hash text;

COMMENT ON COLUMN devices.previous_refresh_token_hash
    IS '上一个刷新令牌的哈希。仅在 refresh_token_rotated_at 之后的宽限期内可用于交换。';
