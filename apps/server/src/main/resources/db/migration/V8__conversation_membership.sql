-- 建表起 conversation_members 就有 role（MEMBER/ADMIN/OWNER）、muted、pinned_at
-- 这些列，但在本次改造之前**没有一行代码读写它们**——运行时既没有建群、加人、
-- 退群的路径，会话全部来自演示种子。这与 users.status 的 'DELETED' 取值曾经的
-- 处境相同（见 AccountDeletionService 的类注释）：schema 里的取值让人相信能力
-- 存在，而能力并不存在。
--
-- 本次迁移补上这套能力唯一缺少的那一列：join_seq。
-- ============================================================

-- ── 为什么需要 join_seq ──────────────────────────────────────
--
-- 没有它的话，"把某人加进群"等同于"把这个群的全部历史消息交给他"——
-- 消息历史查询只按 conversation_id + seq 取数，不区分请求者何时入群。
-- 那意味着任何有加人权限的成员都能通过"拉人进来"泄露此前的全部聊天记录，
-- 且被泄露方（群里的其他人）没有任何感知。
--
-- 这是权限问题而不是体验问题，因此默认取最小可见范围：新成员只能看到
-- 入群之后产生的消息。需要"新成员可见全部历史"的产品形态（类似公开频道）
-- 应当是一个显式的会话属性，而不是因为缺少裁剪而默认获得的行为。
ALTER TABLE conversation_members
    ADD COLUMN join_seq bigint NOT NULL DEFAULT 0 CHECK (join_seq >= 0);

-- 存量成员取默认值 0 = 可见全部历史，这对他们是**正确**的而非将就：
-- 迁移之前不存在加人路径，所以现有的每一个成员都是从会话创建时就在的，
-- 本来就有权看到全部消息。把他们改成"只看得到迁移之后的消息"反而是错的。
COMMENT ON COLUMN conversation_members.join_seq IS
    '加入时的会话序号。历史消息查询以此为下界，使成员看不到入群前的消息。'
    '0 表示可见全部历史——建表即在场的成员取此值。';

-- 退群是软删（left_at 置位）而非删行，因为 read_seq / join_seq 需要保留：
-- 同一个人重新入群时是 UPDATE 而不是 INSERT，此时 join_seq 会被重置为当时的
-- 序号，于是"退群期间的消息"对他同样不可见。这一点用物理删除也能做到，
-- 但软删还保留了"这个人曾经在群里"的事实，成员变更的审计需要它。
--
-- 复活成员的写入路径依赖主键 (conversation_id, user_id) 做 ON CONFLICT，
-- 该主键建表时已存在，此处无需新增约束。
